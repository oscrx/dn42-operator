	if t9.BGPState != "Active" || t9.State != "start" || t9.HasRoutes {
		t.Errorf("tech9: %+v", t9)
	}
	if ps["device1"].Proto != "Device" || ps["device1"].BGPState != "" {
		t.Errorf("device1: %+v", ps["device1"])
	}
	if _, err := c.Command(ctx, "show\nstatus"); err == nil {
		t.Error("newline accepted")
	}
