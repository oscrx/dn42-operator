func testPeer() *peer.Peer {
	return &peer.Peer{
		Name:     "iedon",
		ASN:      4242422189,
		Neighbor: netip.MustParseAddr("fe80::2189:177"),
		Link:     dn42v1.LinkValues{Latency: 2, Bandwidth: 24, Crypto: 34},
	}
}

func TestRender(t *testing.T) {
	got, err := Renderer{Template: "dnpeers"}.Render(testPeer())
	if err != nil {
		t.Fatal(err)
	}
	want := `# Generated by dn42-operator from DN42Peer iedon. Do not edit.
protocol bgp peer_iedon from dnpeers {
  description "AS4242422189 iedon";
  neighbor fe80::2189:177 as 4242422189;
  interface "wg-iedon";
  ipv6 {
    import where dn42_import(2, 24, 34);
    export where dn42_export(2, 24, 34);
  };
}
`
	if got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
}

func TestRenderRefusesUntyped(t *testing.T) {
	p := testPeer()
	p.Name = `x"; } protocol`
	if _, err := (Renderer{Template: "dnpeers"}).Render(p); err == nil {
		t.Error("bad name rendered")
	}
	p = testPeer()
	p.Neighbor = netip.MustParseAddr("fd00::1")
	if _, err := (Renderer{Template: "dnpeers"}).Render(p); err == nil {
		t.Error("non link-local neighbor rendered")
	}
	if _, err := (Renderer{Template: "dn peers"}).Render(testPeer()); err == nil {
		t.Error("bad template rendered")
	}
}

// fakeBird serves canned replies on a unix socket.
func fakeBird(t *testing.T, replies map[string]string) string {
	t.Helper()
	dir, err := os.MkdirTemp("", "bird")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(dir) })
	sock := filepath.Join(dir, "b.ctl")
	l, err := net.Listen("unix", sock)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = l.Close() })
	go func() {
		for {
			c, err := l.Accept()
			if err != nil {
				return
			}
			go func(c net.Conn) {
				defer func() { _ = c.Close() }()
				_, _ = c.Write([]byte("0001 BIRD 2.15 ready.\n"))
				cmd, err := bufio.NewReader(c).ReadString('\n')
				if err != nil {
					return
				}
				rep, ok := replies[strings.TrimSpace(cmd)]
				if !ok {
					rep = "9001 Parse error\n"
				}
				_, _ = c.Write([]byte(rep))
			}(c)
		}
	}()
	return sock
}

