// Package bird renders per-peer BIRD snippets, writes them to the peers
// directory and reloads BIRD over its control socket.
package bird

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/oscrx/dn42-operator/internal/peer"
)

var identRe = regexp.MustCompile(`^[a-zA-Z_][a-zA-Z0-9_]{0,63}$`)

// ValidIdentifier reports whether s is a plain BIRD symbol name.
func ValidIdentifier(s string) bool { return identRe.MatchString(s) }

// Renderer renders peer snippets that use a template from bird.conf.
type Renderer struct {
	// Template is the "template bgp" every peer protocol uses (dnpeers).
	Template string
	// TransitArg makes the import call dn42_import_transit(latency,
	// bandwidth, crypto, transit_ok) with the transit probe's verdict,
	// instead of dn42_import(latency, bandwidth, crypto). It is a function of
	// its own, not a fourth dn42_import argument, so bird.conf can define it
	// before this is turned on: BIRD checks a new bird.conf against the
	// current snippets and new snippets against the current bird.conf, so a
	// changed signature could never pass either check.
	TransitArg bool
}

// Render returns the snippet for one peer. Every value comes from a typed
// field of peer.Peer: the protocol and interface names are built from the
// validated name, the ASN and link values are integers and the neighbor is a
// netip.Addr. Nothing free-form is written.
func (r Renderer) Render(p *peer.Peer) (string, error) {
	if !ValidIdentifier(r.Template) {
		return "", fmt.Errorf("bird template %q is not a plain identifier", r.Template)
	}
	if err := peer.ValidateName(p.Name); err != nil {
		return "", err
	}
	if !p.Neighbor.Is6() || !p.Neighbor.IsLinkLocalUnicast() || p.Neighbor.Zone() != "" {
		return "", fmt.Errorf("neighbor %s is not link-local", p.Neighbor)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by dn42-operator from DN42Peer %s. Do not edit.\n", p.Name)
	fmt.Fprintf(&b, "protocol bgp %s from %s {\n", p.Protocol(), r.Template)
	fmt.Fprintf(&b, "  description \"AS%d %s\";\n", p.ASN, p.Name)
	fmt.Fprintf(&b, "  neighbor %s as %d;\n", p.Neighbor, p.ASN)
	fmt.Fprintf(&b, "  interface \"%s\";\n", p.Interface())
	fmt.Fprintf(&b, "  ipv6 {\n")
	if r.TransitArg {
		fmt.Fprintf(&b, "    import where dn42_import_transit(%d, %d, %d, %t);\n", p.Link.Latency, p.Link.Bandwidth, p.Link.Crypto, !p.NoTransit)
	} else {
		fmt.Fprintf(&b, "    import where dn42_import(%d, %d, %d);\n", p.Link.Latency, p.Link.Bandwidth, p.Link.Crypto)
	}
	fmt.Fprintf(&b, "    export where dn42_export(%d, %d, %d);\n", p.Link.Latency, p.Link.Bandwidth, p.Link.Crypto)
	fmt.Fprintf(&b, "  };\n")
	fmt.Fprintf(&b, "}\n")
	return b.String(), nil
}
